def compiler_indicateurs_avances_et_seuils(historique_tours_dict):
    print("[Étape 2] Calcul des indicateurs dérivés et enrichissement militaire/géopolitique...")
    lignes_globales = []
    for tour_id, j_dict in historique_tours_dict.items():
        for jid, data in j_dict.items():
            puis = float(data.get("puissance", 0.0))
            pop = float(data.get("pop", 0.0))
            cent = float(data.get("centaures", 0.0))
            impact_val = puis - pop - cent

            lignes_globales.append({
                "tour_id": int(tour_id), "joueur_id": str(jid),
                "nom": data.get("nom"), "race": data.get("race"),
                "planetes": int(data.get("planetes", 0)), "centaures": cent,
                "pop": pop, "puissance": puis, "reputation": float(data.get("reputation", 0.0)),
                "tech_valeur": float(data.get("tech_points", 0.0)),
                "rayonnement_pts": float(data.get("rayonnement_pts", 0.0)),
                "popvs_pts": float(data.get("popvs_pts", 0.0)),
                "offensive_valeur": float(data.get("offensive_pts", 0.0)), "impact": impact_val
            })

    df = pd.DataFrame(lignes_globales)
    if df.empty:
        return historique_tours_dict

    dernier_tour_id = max(historique_tours_dict.keys())
    dernier_tour_dict = historique_tours_dict[dernier_tour_id]
    compteurs_cumules = {}
    for tour_dict in historique_tours_dict.values():
        for jid, data in tour_dict.items():
            compteurs = compteurs_cumules.setdefault(jid, {})
            for nom_compteur in [
                "cumul_technologies_donnees", "cumul_technologies_recues",
                "cumul_centaures_donnes", "cumul_centaures_recus",
                "cumul_planetes_prises", "cumul_planetes_perdues",
                "cumul_lieutenants_achetes", "cumul_lieutenants_morts",
                "cumul_centaures_depenses_lieutenants"
            ]:
                compteurs[nom_compteur] = compteurs.get(nom_compteur, 0) + data.get(nom_compteur, 0)

    for jid, data in dernier_tour_dict.items():
        data.update(compteurs_cumules.get(jid, {}))

    metriques_cibles = ["puissance", "planetes", "pop", "centaures", "reputation", "tech_valeur", "rayonnement_pts", "popvs_pts", "offensive_valeur", "impact"]
    moyennes_globales = {m: float(df[df["tour_id"] == dernier_tour_id][m].mean()) for m in metriques_cibles}

    for jid, data_p in dernier_tour_dict.items():
        df_j = df[df["joueur_id"] == jid].sort_values("tour_id")
        metriques_calc = {}
        if not df_j.empty:
            for m in metriques_cibles:
                valeurs_s = df_j[m].values
                progression = float(valeurs_s[-1] - valeurs_s[-2]) if len(valeurs_s) > 1 else 0.0
                derivee_prog = float(valeurs_s[-1] - 2 * valeurs_s[-2] + valeurs_s[-3]) if len(valeurs_s) > 2 else 0.0
                ecart_type = float(np.std(valeurs_s)) if len(valeurs_s) > 1 else 0.0
                ecart_moyenne = float(valeurs_s[-1] - moyennes_globales[m])
                ath = float(np.max(valeurs_s))
                atl = float(np.min(valeurs_s))
                tours_haut = int(sum(valeurs_s > moyennes_globales[m]))

                metriques_calc[m] = {
                    "progression": progression, "derivee_progression": derivee_prog,
                    "ecart_type": ecart_type, "ecart_moyenne": ecart_moyenne,
                    "all_time_high": ath, "all_time_low": atl, "tours_consecutifs_haut": tours_haut
                }
            data_p["indicateurs_derives"] = metriques_calc

            p_prog = metriques_calc["puissance"]["progression"]
            p_ecart = metriques_calc["puissance"]["ecart_moyenne"]
            tech_prog = metriques_calc["tech_valeur"]["progression"]
            off_val = data_p.get("offensive_pts", 0.0)

            if p_prog < 0 or (p_ecart < -100 and p_prog <= 0):
                statut_alerte = "en déclin"
            elif p_ecart > 200 and (tech_prog > 0 or off_val > 50):
                statut_alerte = "dominant"
            elif p_prog > 0 and (tech_prog > 0 or off_val > 20):
                statut_alerte = "menaçant"
            else:
                statut_alerte = "stable"

            data_p["stat_alerte"] = statut_alerte

    return enrichir_donnees_joueurs(dernier_tour_dict)



