def calculer_streaks(historique_tours_dict, jid, tour_actuel):
    """Calcule les séries en cours pour un joueur à partir de l'historique brut."""
    tours = sorted(historique_tours_dict)
    if not tours:
        return {}

    def valeur(tour_id, cle, default=0):
        return historique_tours_dict[tour_id].get(jid, {}).get(cle, default)

    def longueur_condition(condition):
        longueur = 0
        for index in range(len(tours) - 1, -1, -1):
            if condition(index):
                longueur += 1
            else:
                break
        return longueur

    def variation(index, cle):
        if index == 0:
            return 0.0
        return float(valeur(tours[index], cle, 0.0) - valeur(tours[index - 1], cle, 0.0))

    def streak_variation(cle):
        derniere = variation(len(tours) - 1, cle)
        if derniere == 0:
            return 0, None
        direction = 1 if derniere > 0 else -1
        longueur = 0
        for index in range(len(tours) - 1, 0, -1):
            delta = variation(index, cle)
            if delta == 0 or (delta > 0) != (direction > 0):
                break
            longueur += 1
        return longueur, "hausse" if direction > 0 else "baisse"

    streak_planetes, direction_planetes = streak_variation("planetes")
    streak_centaures, direction_centaures = streak_variation("centaures")

    streaks = {
        "streak_sans_attaque": longueur_condition(
            lambda index: sum(valeur(tours[index], "combats", {}).get(key, 0) for key in ("attaques_lancees", "attaques_subies")) == 0
        ),
        "streak_avec_attaque": longueur_condition(
            lambda index: sum(valeur(tours[index], "combats", {}).get(key, 0) for key in ("attaques_lancees", "attaques_subies")) > 0
        ),
        "streak_achat_lieutenant": longueur_condition(
            lambda index: valeur(tours[index], "cumul_lieutenants_achetes", 0) > 0
        ),
        "streak_don_public": longueur_condition(
            lambda index: valeur(tours[index], "cumul_centaures_donnes", 0) > 0
            or valeur(tours[index], "cumul_technologies_donnees", 0) > 0
        ),
        "streak_variation_planetes": streak_planetes,
        "streak_variation_centaures": streak_centaures,
        "streak_variation_planetes_tendance": direction_planetes,
        "streak_variation_centaures_tendance": direction_centaures
    }

    def seconde_variation(index, cle):
        if index < 2:
            return 0.0
        return variation(index, cle) - variation(index - 1, cle)

    for nom_streak, cle in (
        ("streak_acceleration_pop", "pop"),
        ("streak_acceleration_rayonnement", "rayonnement_pts")
    ):
        derniere = seconde_variation(len(tours) - 1, cle)
        direction = 1 if derniere > 0 else -1 if derniere < 0 else 0
        streaks[nom_streak] = longueur_condition(
            lambda index, cle=cle, direction=direction: direction != 0
            and seconde_variation(index, cle) * direction > 0
        )

    variations_puissance = {}
    for index, tour_id in enumerate(tours):
        for joueur_id in historique_tours_dict[tour_id]:
            if index > 0:
                variations_puissance[joueur_id, tour_id] = (
                    float(historique_tours_dict[tour_id].get(joueur_id, {}).get("puissance", 0.0))
                    - float(historique_tours_dict[tours[index - 1]].get(joueur_id, {}).get("puissance", 0.0))
                )

    top1_par_tour = {}
    for index, tour_id in enumerate(tours):
        if index == 0:
            continue
        candidats = {
            joueur_id: variations_puissance.get((joueur_id, tour_id), 0.0)
            for joueur_id in historique_tours_dict[tour_id]
        }
        if candidats:
            top1_par_tour[tour_id] = max(candidats, key=candidats.get)
    streaks["streak_top1_pv_combat"] = longueur_condition(
        lambda index: tours[index] in top1_par_tour and top1_par_tour[tours[index]] == jid
    )

    return streaks


def construire_matrice_relations_historiques(historique_tours_dict):
    """Agrège toutes les relations dirigées enregistrées depuis le premier tour."""
    relations = {}
    noms_joueurs = {}
    total_tours = len(historique_tours_dict)

    def relation(jid_a, jid_b):
        if jid_a == jid_b:
            return None
        cle = tuple(sorted((str(jid_a), str(jid_b))))
        return relations.setdefault(cle, {
            "combats_donnes": 0,
            "combats_subis": 0,
            "ressources_donnees": 0.0,
            "tours_actifs": set()
        })

    for tour_id, joueurs in sorted(historique_tours_dict.items()):
        for jid, data in joueurs.items():
            jid = str(jid)
            nom = data.get("nom")
            if nom and nom != "-":
                noms_joueurs[jid] = nom

        for jid, data in joueurs.items():
            jid = str(jid)
            combats = data.get("combats", {})
            for cible_id in combats.get("cibles_attaquees", []):
                cible_id = str(cible_id)
                rel = relation(jid, cible_id)
                if rel is None:
                    continue
                joueur_1, joueur_2 = sorted((jid, cible_id))
                if jid == joueur_1:
                    rel["combats_donnes"] += 1
                else:
                    rel["combats_subis"] += 1
                rel["tours_actifs"].add(tour_id)

            for don in data.get("dons_emis", []):
                receveur = don.get("receveur")
                if receveur is None:
                    continue
                receveur = str(receveur)
                rel = relation(jid, receveur)
                if rel is None:
                    continue
                montant = don.get("montant", 0.0)
                if don.get("type_don", "").startswith("Technologie:"):
                    montant = 1.0
                elif don.get("type_don") == "Cession_Planete":
                    montant = float(don.get("nombre", 1))
                try:
                    rel["ressources_donnees"] += float(montant)
                except (TypeError, ValueError):
                    pass
                rel["tours_actifs"].add(tour_id)

    def frequence(relation_data):
        interactions = (
            relation_data["combats_donnes"]
            + relation_data["combats_subis"]
            + relation_data["ressources_donnees"]
        )
        tours_actifs = len(relation_data["tours_actifs"])
        ratio_tours = tours_actifs / max(1, total_tours)
        if ratio_tours >= 0.75 or interactions >= max(10, total_tours * 2):
            return "systématique"
        if ratio_tours >= 0.5 or interactions >= max(5, total_tours):
            return "élevée"
        if ratio_tours >= 0.25 or interactions >= 3:
            return "régulière"
        if interactions >= 2:
            return "occasionnelle"
        return "rare"

    matrice = []
    for (jid_1, jid_2), relation_data in sorted(relations.items()):
        matrice.append({
            "joueur_1": noms_joueurs.get(jid_1, f"Joueur #{jid_1}"),
            "joueur_2": noms_joueurs.get(jid_2, f"Joueur #{jid_2}"),
            "combats_donnes": relation_data["combats_donnes"],
            "combats_subis": relation_data["combats_subis"],
            "ressources_donnees": round(relation_data["ressources_donnees"], 3),
            "frequence_relation": frequence(relation_data)
        })
    return matrice


def detecter_indices_complots_suspects(historique_tours_dict):
    """Détecte les convergences militaires, flux suspects et recoupements."""
    tours = sorted(historique_tours_dict)
    if not tours:
        return []

    noms = {}
    attaques = []
    flux = {}

    def nom_joueur(jid):
        return noms.get(str(jid), f"Joueur #{jid}")

    def seuil_flux(nombre_dons, tours_actifs, volume, total_tours):
        ratio = tours_actifs / max(1, total_tours)
        if nombre_dons >= 10 or (nombre_dons >= 5 and ratio >= 0.5) or volume >= 50000:
            return "critique"
        if nombre_dons >= 6 or (nombre_dons >= 3 and ratio >= 0.4) or volume >= 20000:
            return "élevé"
        if nombre_dons >= 3 or ratio >= 0.25 or volume >= 5000:
            return "modéré"
        return "faible"

    for tour_id in tours:
        joueurs = historique_tours_dict[tour_id]
        for jid, data in joueurs.items():
            jid = str(jid)
            noms[jid] = data.get("nom", f"Joueur #{jid}")
            for cible_id in data.get("combats", {}).get("cibles_attaquees", []):
                attaques.append((tour_id, jid, str(cible_id)))

            for don in data.get("dons_emis", []):
                if don.get("type_don", "").startswith("Technologie:"):
                    volume = 1.0
                elif don.get("type_don") == "Centaures":
                    volume = float(don.get("montant", 0.0))
                elif don.get("type_don") == "Cession_Planete":
                    volume = float(don.get("nombre", 1))
                else:
                    continue
                receveur = don.get("receveur")
                if receveur is None or str(receveur) == jid:
                    continue
                cle = (jid, str(receveur))
                donnees_flux = flux.setdefault(cle, {"dons": 0, "volume": 0.0, "tours": set()})
                donnees_flux["dons"] += 1
                donnees_flux["volume"] += volume
                donnees_flux["tours"].add(tour_id)

    alertes = []

    tours_observes = tours[-3:] if len(tours) >= 3 else tours
    attaques_fenetre = [attaque for attaque in attaques if attaque[0] in tours_observes]
    cibles_par_attaquant = {}
    for tour_id, attaquant, cible in attaques_fenetre:
        cibles_par_attaquant.setdefault(attaquant, {}).setdefault(cible, set()).add(tour_id)

    convergences = {}
    for attaquant, cibles in cibles_par_attaquant.items():
        if any(
            historique_tours_dict[tour_id].get(attaquant, {}).get("alliance", "Aucune") != "Aucune"
            for tour_id in tours_observes
        ):
            continue
        for cible, tours_cibles in cibles.items():
            convergences.setdefault(("joueur", cible), {}).setdefault(attaquant, set()).update(tours_cibles)
            for tour_id in tours_observes:
                alliance = historique_tours_dict[tour_id].get(cible, {}).get("alliance", "Aucune")
                if alliance != "Aucune":
                    convergences.setdefault(("alliance", alliance), {}).setdefault(attaquant, set()).update(tours_cibles)

    for (type_cible, cible), attaquants in convergences.items():
        participants = [jid for jid, tours_cibles in attaquants.items() if len(tours_cibles) >= len(tours_observes)]
        if len(participants) < 2:
            continue
        if type_cible == "alliance":
            cible_texte = f"les membres de l'alliance publique '{cible}'"
        else:
            cible_texte = f"le commandant {nom_joueur(cible)}"
        alertes.append({
            "type_alerte": "Convergence d'agression sur une même alliance" if type_cible == "alliance" else "Convergence d'agression sur un même commandant",
            "seuil_alerte": "élevé" if len(participants) >= 3 else "modéré",
            "attaquants": [nom_joueur(jid) for jid in participants],
            "cible": nom_joueur(cible) if type_cible == "joueur" else cible,
            "tours_observes": len(tours_observes),
            "description": f"Ces commandants sans lien officiel attaquent {cible_texte} depuis {len(tours_observes)} tour(s)."
        })

    alertes_transactions = []
    for (donneur, receveur), donnees in flux.items():
        seuil = seuil_flux(donnees["dons"], len(donnees["tours"]), donnees["volume"], len(tours))
        if donnees["dons"] < 3 and donnees["volume"] < 5000:
            continue
        alertes_transactions.append({
            "type_alerte": "Transaction occulte",
            "seuil_alerte": seuil,
            "membres_soupconnes": [nom_joueur(donneur), nom_joueur(receveur)],
            "nombre_dons": donnees["dons"],
            "tours_actifs": len(donnees["tours"]),
            "volume_total": round(donnees["volume"], 3),
            "description": (
                f"{nom_joueur(donneur)} transfère régulièrement des ressources à {nom_joueur(receveur)} "
                f"sur {len(donnees['tours'])} tour(s), pour un volume cumulé de {round(donnees['volume'], 3)}."
            )
        })
    alertes.extend(alertes_transactions)

    cibles_communes = {}
    for (donneur, receveur), donnees in flux.items():
        if donneur > receveur:
            continue
        cibles_donneur = {cible for _, attaquant, cible in attaques_fenetre if attaquant == donneur}
        cibles_receveur = {cible for _, attaquant, cible in attaques_fenetre if attaquant == receveur}
        cibles_communes[(donneur, receveur)] = cibles_donneur & cibles_receveur
    for (donneur, receveur), cibles in cibles_communes.items():
        if not cibles:
            continue
        donnees = flux[(donneur, receveur)]
        alertes.append({
            "type_alerte": "Alliance secrète suspectée",
            "seuil_alerte": seuil_flux(donnees["dons"], len(donnees["tours"]), donnees["volume"], len(tours)),
            "membres_soupconnes": [nom_joueur(donneur), nom_joueur(receveur)],
            "cibles_communes": [nom_joueur(cible) for cible in sorted(cibles)],
            "description": (
                f"Ces deux commandants affichent un historique de dons répétés, tout en coordonnant "
                f"leurs attaques sur des cibles communes au cours des {len(tours_observes)} derniers tours."
            )
        })
    return alertes

