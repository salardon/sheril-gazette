def generer_structs_json_joueurs_avancees(dernier_tour_dict):
    print("\n--- [DEBUG] Début de l'analyse avancée des outliers ---")
    joueurs_json_list = []

    def variation(data, metrique):
        return float(data.get("indicateurs_derives", {}).get(metrique, {}).get("progression", 0.0))

    def rang(metrique):
        valeurs = sorted(
            ((float(data.get(metrique, 0.0)), jid) for jid, data in dernier_tour_dict.items()),
            reverse=True
        )
        return {jid: index + 1 for index, (_, jid) in enumerate(valeurs)}

    rang_puissance = rang("puissance")
    rang_technologie = rang("tech_points")
    compteurs = list(COMPTEURS_CUMULES)
    moyennes_compteurs = {
        compteur: float(np.mean([data.get(compteur, 0) for data in dernier_tour_dict.values()]))
        for compteur in compteurs
    }

    def nettoyer(valeur):
        if isinstance(valeur, dict):
            return {
                cle: nettoyee for cle, item in valeur.items()
                if (nettoyee := nettoyer(item)) not in (None, {}, [], "")
            }
        if isinstance(valeur, list):
            return [item for item in (nettoyer(item) for item in valeur) if item not in (None, {}, [], "")]
        return valeur

    # Étape A : Transformation des indicateurs dérivés en DataFrame pour analyse globale
    lignes_analyse = []
    for jid, data in dernier_tour_dict.items():
        nom = data.get("nom", "Inconnu")
        ind_derives = data.get("indicateurs_derives", {})
        row = {"joueur_id": jid, "nom": nom, "race": data.get("race", "-")}

        for metrique, stats in ind_derives.items():
            row[f"{metrique}_prog"] = stats.get("progression", 0.0)
            row[f"{metrique}_ecart"] = stats.get("ecart_moyenne", 0.0)
            row[f"{metrique}_ath"] = stats.get("all_time_high", 0.0)
            row[f"{metrique}_derivee"] = stats.get("derivee_progression", 0.0)
        lignes_analyse.append(row)

    df_outliers = pd.DataFrame(lignes_analyse)
    print(f"[DEBUG] DataFrame d'analyse construit avec {len(df_outliers)} joueurs et {len(df_outliers.columns)} colonnes.")

    # Étape B : Utilisation d'un Isolation Forest si le nombre de joueurs est suffisant
    anomalies_ids = set()
    if len(df_outliers) > 3:
        features_cols = [c for c in df_outliers.columns if c not in ["joueur_id", "nom", "race"]]
        X = df_outliers[features_cols].fillna(0)

        iso = IsolationForest(contamination=0.15, random_state=42)
        df_outliers["is_anomaly"] = iso.fit_predict(X)

        anomalies_df = df_outliers[df_outliers["is_anomaly"] == -1]
        anomalies_ids = set(anomalies_df["joueur_id"])

        print(f"[DEBUG] Isolation Forest a détecté {len(anomalies_ids)} anomalie(s) globale(s).")
    else:
        print("[DEBUG] Pas assez de joueurs pour exécuter Isolation Forest (<= 3).")

    # Étape C : Construction du JSON final par joueur incluant tous les indicateurs avancés
    for jid, data in dernier_tour_dict.items():
        nom = data.get("nom", "Inconnu")
        race = data.get("race", "-")
        ind_derives = data.get("indicateurs_derives", {})

        print(f"\n[DEBUG] Analyse du joueur : {nom}")
        outliers = []

        for metrique, stats in ind_derives.items():
            prog = stats.get("progression", 0.0)
            ecart = stats.get("ecart_moyenne", 0.0)
            derivee = stats.get("derivee_progression", 0.0)
            ath = stats.get("all_time_high", 0.0)
            tours_haut = stats.get("tours_haut", [])

            # 1. Progression brute significative
            if abs(prog) > 50:
                signe = "+" if prog > 0 else ""
                outliers.append(f"{signe}{int(prog)} {metrique} (Progression tour actuel)")

            # 2. Écart massif par rapport à la moyenne du groupe
            if abs(ecart) > 150:
                signe = "+" if ecart > 0 else ""
                outliers.append(f"{signe}{int(ecart)} {metrique} (Écart structurel vs moyenne)")

            # 3. Dérivée (accélération ou freinage brutal)
            if abs(derivee) > 30:
                signe = "+" if derivee > 0 else ""
                outliers.append(f"Cassure/Accélération {metrique} (Dérivée: {signe}{int(derivee)})")

            # 4. All-Time High / Records historiques ou Tours Haut
            if ath != 0 and abs(prog) > 0 and (prog >= ath * 0.95):
                outliers.append(f"Record historique approché/battu pour {metrique} (ATH: {int(ath)})")
            elif tours_haut:
                # Si le joueur truste les sommets historiques
                outliers.append(f"Habitué des sommets sur {metrique} (Tours hauts enregistrés)")

        if jid in anomalies_ids:
            outliers.append("Profil global atypique (Détecté par IA multi-critères)")

        # Dédoublonnage et limitation pour garder l'essence narrative
        outliers = list(dict.fromkeys(outliers))[:5]
        print(f"  => Total outliers retenus pour {nom} : {len(outliers)}")

        # --- MODIFICATION ICI : Conversion des ID cibles en Noms ---
        cibles_brutes = data.get("combats", {}).get("cibles_attaquees", [])
        combats_recus = []
        for cible_id in cibles_brutes:
            nom_cible = dernier_tour_dict.get(str(cible_id), {}).get("nom", f"Joueur #{cible_id}")
            combats_recus.append(f"Cible attaquée : {nom_cible}")
        # -------------------------------------------------------------

        dons_financiers = [f"A versé un don vers {don.get('receveur_nom', 'inconnu')}" for don in data.get("dons_emis", [])]

        indicateurs_clefs = {
            "planetes": {
                "valeur": int(data.get("planetes", 0)),
                "variation": variation(data, "planetes")
            },
            "puissance": {
                "valeur": float(data.get("puissance", 0.0)),
                "variation": variation(data, "puissance"),
                "rang": rang_puissance.get(jid)
            },
            "score_technologique": {
                "valeur": float(data.get("tech_points", 0.0)),
                "variation": variation(data, "tech_valeur"),
                "rang": rang_technologie.get(jid)
            },
            "impact": {
                "valeur": int(data.get("puissance", 0) - data.get("pop", 0) - data.get("centaures", 0)),
                "variation": variation(data, "impact")
            }
        }
        for indicateur in indicateurs_clefs.values():
            indicateur["variation_formatee"] = f"{indicateur['variation']:+g}"

        compteurs_marquants = sorted(
            (
                {
                    "nom": compteur,
                    "valeur": data.get(compteur, 0),
                    "ecart_moyenne": data.get(compteur, 0) - moyennes_compteurs[compteur]
                }
                for compteur in compteurs
            ),
            key=lambda item: abs(item["ecart_moyenne"]),
            reverse=True
        )[:5]
        series_encours = sorted(
            (
                {
                    "nom": nom,
                    "longueur": longueur,
                    **({"tendance": data["streaks"].get(f"{nom}_tendance")} if nom in ["streak_variation_planetes", "streak_variation_centaures"] else {})
                }
                for nom, longueur in data.get("streaks", {}).items()
                if nom in STREAKS and isinstance(longueur, (int, float)) and longueur > 0
            ),
            key=lambda item: item["longueur"],
            reverse=True
        )[:3]

        structure_joueur = {
            "joueur": nom,
            "race": race,
            "alliance": data.get("indicateurs_geopolitiques", {}).get("alliance", data.get("alliance", "Aucune")),
            "isolement": float(data.get("indicateurs_geopolitiques", {}).get("est_isole", 1.0)),
            "indicateurs_clefs": indicateurs_clefs,
            "fait_marquant_outliers": outliers,
            "evenements_du_tour": data.get("evenements_du_tour", []),
            "historique_et_seuils": {
                "seuils_franchis_ce_tour": data.get("seuils_franchis", []),
                "compteurs_marquants": compteurs_marquants,
                "series_encours": series_encours
            },
        }
        joueurs_json_list.append(nettoyer(structure_joueur))

    print("\n--- [DEBUG] Fin de l'analyse avancée ---\n")
    return joueurs_json_list

