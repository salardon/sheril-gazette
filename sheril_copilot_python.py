def get_latest_turns_and_download():
    print("[Étape 0] Recherche incrémentale des tours disponibles...")
    session = requests.Session()
    session.headers.update({
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36",
        "Referer": "https://sheril.pbem-france.net/"
    })

    tour_actuel = PREMIER_TOUR
    dernier_tour_trouve = None

    while True:
        url_zip = BASE_ZIP_URL.replace("{NUM}", str(tour_actuel))
        response = session.get(url_zip, allow_redirects=False)
        if response.status_code == 404 or not response.ok:
            break
        dernier_tour_trouve = tour_actuel
        tour_actuel += 1

    if not dernier_tour_trouve:
        return []

    print(f"[Étape 0] Dernier tour détecté -> Tour {dernier_tour_trouve}.")
    tours_a_traiter = list(range(PREMIER_TOUR, dernier_tour_trouve + 1))

    os.makedirs(BASE_EXTRACT_DIR, exist_ok=True)
    tours_valides = []

    for t in tours_a_traiter:
        url_zip = BASE_ZIP_URL.replace("{NUM}", str(t))
        response = session.get(url_zip)
        if response.ok:
            zip_filename = f"temp_tour_{t}.zip"
            with open(zip_filename, "wb") as f:
                f.write(response.content)

            tour_dir = os.path.join(BASE_EXTRACT_DIR, f"tour_{t}")
            os.makedirs(tour_dir, exist_ok=True)

            with zipfile.ZipFile(zip_filename, 'r') as zip_ref:
                zip_ref.extractall(tour_dir)
            os.remove(zip_filename)
            tours_valides.append(t)

    return tours_valides

def parse_tour_files(tour_id):
    print(f"\n[Étape 1] Parsing complet du Tour {tour_id}...")
    joueurs_dict = {}
    tour_dir = os.path.join(BASE_EXTRACT_DIR, f"tour_{tour_id}")

    if not os.path.exists(tour_dir):
        return joueurs_dict

    for root, dirs, files in os.walk(tour_dir):
        for file in files:
            file_lower = file.lower()
            if file_lower not in PARSERS_REGISTRY:
                continue

            file_path = os.path.join(root, file)
            try:
                with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
                    soup = BeautifulSoup(f.read(), 'html.parser')

                parser_func = PARSERS_REGISTRY[file_lower]
                metric_values = parser_func(soup, tour_id)

                if metric_values is None:
                    continue

                if file_lower == "evt.htm":
                    if isinstance(metric_values, dict) and "dons_emis" in metric_values:
                        for don in metric_values["dons_emis"]:
                            jid_emetteur = str(don.get("emetteur"))
                            if jid_emetteur and jid_emetteur != "None":
                                if jid_emetteur not in joueurs_dict:
                                    joueurs_dict[jid_emetteur] = init_player_structure(tour_id, jid_emetteur, don.get("emetteur_nom", "-"), "-")
                                if "dons_emis" not in joueurs_dict[jid_emetteur]:
                                    joueurs_dict[jid_emetteur]["dons_emis"] = []
                                joueurs_dict[jid_emetteur]["dons_emis"].append(don)
                                if don.get("type_don", "").startswith("Technologie:"):
                                    joueurs_dict[jid_emetteur]["cumul_technologies_donnees"] += 1
                                    jid_receveur = str(don.get("receveur"))
                                    if jid_receveur and jid_receveur != "None":
                                        if jid_receveur not in joueurs_dict:
                                            joueurs_dict[jid_receveur] = init_player_structure(
                                                tour_id, jid_receveur, don.get("receveur_nom", "-"), "-"
                                            )
                                        joueurs_dict[jid_receveur]["cumul_technologies_recues"] += 1
                                elif don.get("type_don") == "Centaures":
                                    joueurs_dict[jid_emetteur]["cumul_centaures_donnes"] += float(don.get("montant", 0.0))
                                    jid_receveur = str(don.get("receveur"))
                                    if jid_receveur and jid_receveur != "None":
                                        if jid_receveur not in joueurs_dict:
                                            joueurs_dict[jid_receveur] = init_player_structure(
                                                tour_id, jid_receveur, don.get("receveur_nom", "-"), "-"
                                            )
                                        joueurs_dict[jid_receveur]["cumul_centaures_recus"] += float(don.get("montant", 0.0))
                                elif don.get("type_don") == "Achat_Lieutenant":
                                    joueurs_dict[jid_emetteur]["cumul_lieutenants_achetes"] += 1
                                    joueurs_dict[jid_emetteur]["cumul_centaures_depenses_lieutenants"] += float(don.get("montant", 0.0))
                                elif don.get("type_don") == "Mort_Lieutenant":
                                    joueurs_dict[jid_emetteur]["cumul_lieutenants_morts"] += 1
                    continue

                for jid, r in metric_values.items():
                    jid = str(r.get("joueur_id", jid))
                    if jid not in joueurs_dict:
                        joueurs_dict[jid] = init_player_structure(tour_id, jid, r.get("nom", "-"), r.get("race", "-"))

                    if file_lower == "planetes.htm":
                        joueurs_dict[jid]["planetes"] = int(r.get("planetes", 0))
                    elif file_lower == "centaures.htm":
                        joueurs_dict[jid]["centaures"] = float(r.get("valeur", 0.0))
                    elif file_lower == "pop.htm":
                        joueurs_dict[jid]["pop"] = float(r.get("valeur", 0.0))
                    elif file_lower == "puissance.htm":
                        joueurs_dict[jid]["puissance"] = float(r.get("valeur", 0.0))
                    elif file_lower == "reputation.htm":
                        joueurs_dict[jid]["reputation"] = float(r.get("valeur", 0.0))
                    elif file_lower == "technologie.htm":
                        joueurs_dict[jid]["tech_points"] = float(r.get("valeur", 0.0))
                    elif file_lower == "rayonnement.htm":
                        joueurs_dict[jid]["rayonnement_pts"] = float(r.get("valeur", 0.0))
                    elif file_lower == "pop_vs.htm":
                        joueurs_dict[jid]["popvs_pts"] = float(r.get("valeur", 0.0))
                    elif file_lower == "offensive.htm":
                        joueurs_dict[jid]["offensive_pts"] = float(r.get("valeur", 0.0))
                    elif file_lower == "combats.htm":
                        if "combats" in r:
                            joueurs_dict[jid]["combats"] = r["combats"]
                            joueurs_dict[jid]["cumul_planetes_prises"] = int(r["combats"].get("planetes_prises", 0))
                            joueurs_dict[jid]["cumul_planetes_perdues"] = int(r["combats"].get("planetes_perdues", 0))
                    elif file_lower in ["alliances.htm", "alliance.htm"]:
                        if "alliance" in r:
                            joueurs_dict[jid]["alliance"] = str(r["alliance"])

                    if r.get("nom", "-") not in ["-", ""]:
                        joueurs_dict[jid]["nom"] = r["nom"]
                    if r.get("race", "-") not in ["-", ""]:
                        joueurs_dict[jid]["race"] = r["race"]
            except Exception as e:
                print(f"[Diag-Parsing] Erreur sur '{file}' (Tour {tour_id}) : {e}")

    return joueurs_dict

